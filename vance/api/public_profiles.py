@router.get("/profiles/{slug}/intro-status/{user_id}")
async def get_intro_request_status(slug: str, user_id: str):
    """
    Check the status of an intro request and voice call.
    
    Returns:
    {
        "call_status": "initiated" | "completed" | "not_found",
        "intro_requested": true/false,
        "whatsapp_link": "https://wa.me/..." (if call completed)
    }
    """
    try:
        # Check call status
        call_doc = fs.collection("profile_intro_calls").document(user_id).get()
        call_status = "not_found"
        intro_requested = False
        
        if call_doc.exists:
            call_data = call_doc.to_dict() or {}
            call_status = call_data.get("status", "initiated")
            
            # Check if call has completed (look for extraction data or call completion)
            extraction_doc = fs.collection("extractions").document(user_id).get()
            if extraction_doc.exists:
                call_status = "completed"
                intro_requested = call_data.get("intro_requested", False)
        
        # Get candidate user_id from slug
        profile = _get_profile_by_slug(slug)
        if not profile:
            raise HTTPException(status_code=404, detail="Profile not found")
        
        candidate_user_id = profile.get("userId")
        
        # Always use fixed WhatsApp link
        whatsapp_link = "https://shorturl.at/oxUJt"
        
        if call_status == "completed":
            # Check if intro was already requested
            intro_requests = fs.collection("intro_requests").where("requester_uid", "==", user_id).where("candidate_uid", "==", candidate_user_id).limit(1).stream()
            intro_requested = any(True for _ in intro_requests)
            
            if not intro_requested:
                # Auto-send intro request after call completion
                try:
                    from utils.whatsapp.whatsapp import WhatsAppSender
                    from utils.whatsapp.components import MsgComponents
                    from utils.db import get_user_profile
                    
                    user_profile = get_user_profile(user_id) or {}
                    requester_name = user_profile.get("name", "Someone")
                    requester_linkedin = user_profile.get("linkedin_url") or user_profile.get("linkedin") or ""
                    
                    # Get candidate's WhatsApp ID
                    candidate_profile_data = get_user_profile(candidate_user_id) or {}
                    candidate_wa_id = (
                        candidate_profile_data.get("wa_id")
                        or candidate_profile_data.get("phone")
                        or candidate_profile_data.get("whatsapp")
                        or candidate_user_id
                    )
                    
                    # Format message: "Name, LinkedIn, has requested intro. Do you want to connect?"
                    if requester_linkedin:
                        intro_message = f"{requester_name}, {requester_linkedin}, has requested intro. Do you want to connect?"
                    else:
                        intro_message = f"{requester_name} has requested intro. Do you want to connect?"
                    
                    sender = WhatsAppSender()
                    payload = MsgComponents.text_scaffold(to=candidate_wa_id, text=intro_message)
                    sender.send(data=payload)
                    
                    # Save intro request
                    intro_request = {
                        "requester_uid": user_id,
                        "requester_name": requester_name,
                        "candidate_uid": candidate_user_id,
                        "candidate_name": profile.get("name", "Candidate"),
                        "status": "pending",
                        "requested_at": time.time(),
                        "source": "profile_page",
                    }
                    fs.collection("intro_requests").add(intro_request)
                    
                    # Update call tracking
                    fs.collection("profile_intro_calls").document(user_id).update({
                        "intro_requested": True,
                        "intro_requested_at": time.time(),
                    })
                    
                    intro_requested = True
                except Exception as e:
                    print(f"⚠️ [INTRO_REQUEST] Error auto-sending intro request: {e}")
        
        # Always return fixed WhatsApp link
        return JSONResponse({
            "call_status": call_status,
            "intro_requested": intro_requested,
            "whatsapp_link": "https://shorturl.at/oxUJt" if call_status == "completed" else None,
        })
    except Exception as e:
        print(f"❌ [INTRO_REQUEST] Error checking status: {e}")
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=f"Error checking status: {str(e)}")


