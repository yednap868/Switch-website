"""
Public candidate profiles API.

Exposes public, slug-based profile endpoints like:
    GET /api/public/profiles/{slug}

These are intended to power URLs like:
    https://www.vance.so/{slug}
"""

from typing import Any, Dict, Optional
import time

from fastapi import APIRouter, HTTPException
from fastapi.responses import JSONResponse, Response

from utils.db import fs


router = APIRouter(prefix="/api/public", tags=["Public Profiles"])


def _get_profile_by_slug(slug: str) -> Optional[Dict[str, Any]]:
    """
    Resolve a public slug to a candidate profile payload suitable for the frontend UI.
    """
    # 1. Resolve slug → user_id mapping from public_profiles collection
    mapping_ref = fs.collection("public_profiles").document(slug)
    mapping_doc = mapping_ref.get()

    if not mapping_doc.exists:
        return None

    mapping_data = mapping_doc.to_dict() or {}
    if not mapping_data.get("active", True):
        return None

    user_id = mapping_data.get("user_id")
    if not user_id:
        return None

    # 2. Load canonical profile from user_profiles
    profile_ref = fs.collection("user_profiles").document(user_id)
    profile_doc = profile_ref.get()
    if not profile_doc.exists:
        return None

    profile_data = profile_doc.to_dict() or {}
    extraction_data = profile_data.get("extraction_data", {}) or {}

    name = profile_data.get("name") or extraction_data.get("name") or ""
    linkedin_url = (
        profile_data.get("linkedin_url")
        or extraction_data.get("linkedin_url")
        or ""
    )

    # Core fields for the UI
    role = extraction_data.get("target_role", "")
    experience = extraction_data.get("work_experience", "")
    location = extraction_data.get("current_location", "")

    avatar_url = (
        profile_data.get("avatar_url") or extraction_data.get("avatar_url") or ""
    )

    # Prefer high-signal fields from profile_data (generated by Claude), fallback to extraction_data
    story = (
        profile_data.get("story")
        or extraction_data.get("the_story")
        or extraction_data.get("work_experience")
        or ""
    )

    # Strengths: prefer high-signal generated list, fallback to building from extraction_data
    strengths = profile_data.get("strengths", [])
    if not strengths:
        # Fallback: build from raw extraction fields
        core_skills = extraction_data.get("core_skills")
        if core_skills:
            strengths.append(
                {
                    "text": str(core_skills),
                    "hasAudio": False,
                }
            )

        key_projects = extraction_data.get("key_projects")
        if key_projects:
            strengths.append(
                {
                    "text": str(key_projects),
                    "hasAudio": False,
                }
            )

        motivations = extraction_data.get("motivations")
        if motivations:
            strengths.append(
                {
                    "text": str(motivations),
                    "hasAudio": False,
                }
            )

    # Proof of work: prefer high-signal generated list
    proof_of_work = profile_data.get("proofOfWork", []) or profile_data.get(
        "proof_of_work", []
    )

    # Thoughts: prefer high-signal generated list
    thoughts = profile_data.get("thoughts", [])

    # Audio clips: best-effort – may be empty if not yet attached
    intro_audio_url = profile_data.get("intro_audio_url") or ""
    thinking_audio_url = profile_data.get("thinking_audio_url") or ""
    
    # If audio is stored as conversation_id only (too large for Firestore), return endpoint URL
    audio_conversation_id = profile_data.get("audio_conversation_id") or ""
    audio_available = profile_data.get("audio_available", False)
    
    # CRITICAL: Only use base64 audio URLs if we have a verified conversation_id
    # If base64 audio exists but no conversation_id, we cannot verify ownership - clear it
    has_base64_audio = (intro_audio_url and intro_audio_url.startswith("data:audio")) or (thinking_audio_url and thinking_audio_url.startswith("data:audio"))
    if has_base64_audio and (not audio_conversation_id or audio_conversation_id == "missing"):
        print(f"⚠️ [PROFILE_API] Found base64 audio without conversation_id for {user_id} - cannot verify ownership, clearing base64 audio")
        intro_audio_url = ""
        thinking_audio_url = ""
    
    # Check if we need to construct audio URLs from conversation_id
    # If intro_audio_url is empty/falsy AND we have a valid conversation_id, construct the URLs
    has_valid_audio_url = intro_audio_url and intro_audio_url.strip() and intro_audio_url.startswith(("http://", "https://", "data:"))
    
    # Try to find conversation_id from call history if not in profile
    if not has_valid_audio_url and (not audio_conversation_id or audio_conversation_id == "missing"):
        try:
            calls_ref = fs.collection("user_calls").document(user_id).collection("calls")
            # Try to get recent calls
            try:
                calls = calls_ref.order_by("timestamp", direction="DESCENDING").limit(5).stream()
            except:
                calls = calls_ref.limit(5).stream()
            
            for call_doc in calls:
                call_data = call_doc.to_dict() or {}
                found_conv_id = call_data.get("conversation_id") or call_data.get("call_id")
                if found_conv_id and found_conv_id.strip() and found_conv_id.startswith("conv_"):
                    audio_conversation_id = found_conv_id.strip()
                    print(f"✅ [PROFILE_API] Found conversation_id from call history: {audio_conversation_id}")
                    break
        except Exception as e:
            print(f"⚠️ [PROFILE_API] Error finding conversation_id from call history: {e}")
    
    # Also check if we have a conversation_id stored (even if audio_available is False, try to fetch)
    # CRITICAL: Only return audio if conversation_id is verified to belong to this user
    if not has_valid_audio_url and audio_conversation_id and audio_conversation_id.strip() and audio_conversation_id.startswith("conv_"):
        # Verify ownership before returning audio
        from services.profile_audio_service import profile_audio_service
        is_owner = profile_audio_service._verify_conversation_ownership(audio_conversation_id, user_id)
        
        if is_owner:
            # Audio verified - return endpoint URL for on-demand fetching
            base_url = "https://api.relayy.world"
            intro_audio_url = f"{base_url}/api/public/audio/{audio_conversation_id}?segment=intro"
            thinking_audio_url = f"{base_url}/api/public/audio/{audio_conversation_id}?segment=thinking"
            audio_available = True
            print(f"✅ [PROFILE_API] Verified conversation_id ownership for {user_id}, returning audio URLs")
        else:
            # Audio does not belong to this user - don't return it
            print(f"⚠️ [PROFILE_API] conversation_id={audio_conversation_id} does NOT belong to user_id={user_id}, NOT returning audio")
            intro_audio_url = ""
            thinking_audio_url = ""
            audio_available = False
    
    # Final check: If we have base64 audio URLs, verify they belong to this user via conversation_id
    if (intro_audio_url and intro_audio_url.startswith("data:audio")) or (thinking_audio_url and thinking_audio_url.startswith("data:audio")):
        if not audio_conversation_id or audio_conversation_id == "missing":
            # Base64 audio without conversation_id - cannot verify, don't return
            print(f"⚠️ [PROFILE_API] Base64 audio exists but no conversation_id to verify ownership for {user_id}, clearing audio")
            intro_audio_url = ""
            thinking_audio_url = ""
        else:
            # Verify ownership even for base64 audio
            from services.profile_audio_service import profile_audio_service
            is_owner = profile_audio_service._verify_conversation_ownership(audio_conversation_id, user_id)
            if not is_owner:
                print(f"⚠️ [PROFILE_API] Base64 audio exists but conversation_id does NOT belong to user_id={user_id}, clearing audio")
                intro_audio_url = ""
                thinking_audio_url = ""
                audio_available = False

    # Opportunities section from extraction data
    industries = extraction_data.get("industry_background")
    industries_list = []
    if isinstance(industries, list):
        industries_list = [str(i) for i in industries]
    elif industries:
        industries_list = [str(industries)]

    opportunities = {
        "role": role,
        "industries": industries_list,
        "companyStage": extraction_data.get("company_stage", ""),
    }

    # Verification: If profile exists in public_profiles and is active, it's verified 100%
    # Check if this profile exists in public_profiles (it does since we found it by slug)
    is_verified = mapping_data.get("active", True)  # If we found it by slug, it's active
    
    # If profile is active/verified, set to 100% (score and percentile)
    if is_verified:
        verification_score = 100
        verification_percentile = 100
    else:
        verification_score = profile_data.get("verification_score", 0)
        verification_percentile = profile_data.get("verification_percentile", 0)
    
    verification = {
        "date": profile_data.get("verified_at_display", ""),
        "score": verification_score,
        "percentile": verification_percentile,
    }

    activity = {
        "introductions": profile_data.get("introductions_count", 0),
        "interviewsScheduled": profile_data.get("interviews_scheduled", 0),
        "avgResponseTime": profile_data.get("avg_response_time_display", ""),
    }

    # Demand data – for now driven off introductions count
    demand_data = {
        "introCount": activity["introductions"],
        "days": profile_data.get("activity_window_days", 30),
        "isActive": bool(activity["introductions"]),
    }

    # Final payload shaped to match vance-spotlight/src/pages/Index.tsx expectations
    # Only include fields that have values (filter out empty/missing fields)
    payload = {
        "slug": slug,
        "userId": user_id,
        "name": name,
    }
    
    # Only add fields if they have values
    if role:
        payload["role"] = role
    if experience:
        payload["experience"] = experience
    if location:
        payload["location"] = location
    if avatar_url:
        payload["avatarUrl"] = avatar_url
    if linkedin_url:
        payload["linkedinUrl"] = linkedin_url
    if intro_audio_url:
        payload["introAudioUrl"] = intro_audio_url
    if thinking_audio_url:
        payload["thinkingAudioUrl"] = thinking_audio_url
    if profile_data.get("resume_url"):
        payload["resumeUrl"] = profile_data.get("resume_url")
    if profile_data.get("github_url"):
        payload["githubUrl"] = profile_data.get("github_url")
    
    # Always include demandData, verification, and activity (can be empty/defaults)
    payload["demandData"] = demand_data
    payload["verification"] = verification
    payload["activity"] = activity
    
    # Only add sections if they have content (not empty)
    if story and story.strip():
        payload["story"] = story
    if strengths and len(strengths) > 0:
        payload["strengths"] = strengths
    if proof_of_work and len(proof_of_work) > 0:
        payload["proofOfWork"] = proof_of_work
    if thoughts and len(thoughts) > 0:
        payload["thoughts"] = thoughts
    has_opportunities = (
        (opportunities.get("role") and opportunities["role"].strip()) or
        (opportunities.get("industries") and len(opportunities["industries"]) > 0) or
        (opportunities.get("companyStage") and opportunities["companyStage"].strip())
    )
    if has_opportunities:
        payload["opportunities"] = opportunities
    
    return payload




@router.get("/audio/{conversation_id}")
async def get_audio_by_conversation_id(conversation_id: str, segment: str = "intro"):
    """
    Fetch audio from ElevenLabs by conversation_id.
    Returns trimmed audio segments based on question segments from transcript.
    
    Trimming is based on actual questions asked in the conversation:
    - Intro: Segment where agent asks "tell me about your background" or "tell me about what you're looking for"
    - Thinking: Segment where agent asks "how do you think" or "what do you think" or similar thinking questions
    
    Args:
        conversation_id: ElevenLabs conversation ID
        segment: Audio segment type - "intro" (intro question segment) or "thinking" (thinking question segment)
    """
    from services.profile_audio_service import profile_audio_service
    
    try:
        print(f"🎧 [AUDIO_API] Fetching audio for conversation_id={conversation_id}, segment={segment}")
        
        # Fetch and trim audio based on segment type
        trim_intro = (segment == "intro")
        trim_thinking = (segment == "thinking")
        
        # Find user_id from conversation_id to get transcript
        user_id = None
        try:
            from utils.db import fs
            # Try to find user_id from conversation_id
            # Search for user_id by conversation_id in user_calls (alternative method since collection group might need index)
            # We'll try to find it from user_profiles instead
            profiles_with_conv = fs.collection("user_profiles").where("audio_conversation_id", "==", conversation_id).limit(1).stream()
            for profile_doc in profiles_with_conv:
                user_id = profile_doc.id
                break
        except Exception as e:
            print(f"⚠️ [AUDIO_API] Could not find user_id for conversation_id: {e}")
            # User_id is optional - trimming will use fallback if not found
            pass
        
        intro_audio_url, thinking_audio_url = await profile_audio_service._fetch_audio_from_elevenlabs_api(
            conversation_id, user_id=user_id, trim_intro=trim_intro, trim_thinking=trim_thinking
        )
        
        # Select the appropriate audio segment
        if segment == "intro":
            audio_url = intro_audio_url
        elif segment == "thinking":
            audio_url = thinking_audio_url
        else:
            # Default to intro if invalid segment
            audio_url = intro_audio_url
        
        # If trimming failed, try fetching full audio without trimming
        if not audio_url:
            print(f"⚠️ [AUDIO_API] Trimming failed or returned empty, trying full audio...")
            try:
                intro_audio_url_full, thinking_audio_url_full = await profile_audio_service._fetch_audio_from_elevenlabs_api(
                    conversation_id, user_id=user_id, trim_intro=False, trim_thinking=False
                )
                if segment == "intro":
                    audio_url = intro_audio_url_full or thinking_audio_url_full  # Use any available audio
                elif segment == "thinking":
                    audio_url = thinking_audio_url_full or intro_audio_url_full  # Use any available audio
                else:
                    audio_url = intro_audio_url_full or thinking_audio_url_full
                
                if audio_url:
                    print(f"✅ [AUDIO_API] Successfully fetched full audio as fallback")
            except Exception as e:
                print(f"⚠️ [AUDIO_API] Error fetching full audio: {e}")
        
        if not audio_url:
            print(f"❌ [AUDIO_API] No audio found for {conversation_id}")
            raise HTTPException(status_code=404, detail="Audio not found")
        
        # Extract base64 data from data URL
        if audio_url.startswith("data:audio/mpeg;base64,"):
            base64_data = audio_url.split(",", 1)[1]
            import base64
            audio_bytes = base64.b64decode(base64_data)
            
            print(f"✅ [AUDIO_API] Returning {len(audio_bytes)} bytes of {segment} audio for {conversation_id}")
            
            # Return as MP3 audio file with proper headers
            return Response(
                content=audio_bytes,
                media_type="audio/mpeg",
                headers={
                    "Content-Disposition": f"inline; filename={segment}_audio_{conversation_id}.mp3",
                    "Cache-Control": "public, max-age=3600",
                    "Access-Control-Allow-Origin": "*",  # Allow CORS
                    "Access-Control-Allow-Methods": "GET, OPTIONS",
                }
            )
        else:
            # If it's already a URL, return it as JSON
            return JSONResponse({
                "conversation_id": conversation_id,
                "segment": segment,
                "audio_url": audio_url
            })
    except HTTPException:
        raise
    except Exception as e:
        print(f"❌ [AUDIO_API] Error fetching audio for {conversation_id}: {e}")
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=f"Error fetching audio: {str(e)}")




